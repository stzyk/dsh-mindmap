/**
 * 构建脚本：src/index.ts → lib/index.js（Node ESM），
 *           src/client/index.tsx → lib/client.js（浏览器 CJS + __ModuleLoader__ 包装）。
 *
 * React 系列在 client 打包中保持 external —— 由平台 seed 模块提供；
 * 打进第二份 React 会导致 hooks 崩溃（useState 为 null）。
 *
 * 用法：npm run bundle
 */

import { build } from "esbuild";
import { mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkgName = "dsh-mindmap";

/** 客户端 bundle 的 CJS 包装：与平台 __ModuleLoader__ 约定一致。 */
const clientWrapper = {
  banner:
    `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkgName)}, factory: (require) => {\n` +
    `\tvar module = { exports: {} };\n` +
    `\tvar exports = module.exports;\n`,
  footer: `\treturn module.exports;\n} });\n`,
};

await mkdir(resolve(root, "lib"), { recursive: true });

// Node half：ESM，平台包全部 external。
await build({
  entryPoints: [resolve(root, "src/index.ts")],
  outfile: resolve(root, "lib/index.js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  sourcemap: false,
  logLevel: "info",
  // 中文字面量原样输出：不转义成 \uXXXX，排障时能直接 grep 文案
  charset: "utf8",
  banner: {
    js: `/** ${pkgName} — generated by scripts/build.mjs; do not edit lib/ by hand. */`,
  },
});

// Client half：CJS 包进 __ModuleLoader__，react 系列保持 external。
// 必须是 cjs（而非 iife）：平台 loader 读取 factory 返回的 module.exports。
await build({
  entryPoints: [resolve(root, "src/client/index.tsx")],
  outfile: resolve(root, "lib/client.js"),
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2022",
  jsx: "transform",
  jsxFactory: "React.createElement",
  jsxFragment: "React.Fragment",
  external: ["react", "react/jsx-runtime", "react-dom", "react-dom/client"],
  define: { "process.env.NODE_ENV": '"production"' },
  sourcemap: false,
  charset: "utf8",
  logLevel: "info",
  banner: { js: clientWrapper.banner },
  footer: { js: clientWrapper.footer },
});

console.log(`[build] ${pkgName}: lib/index.js + lib/client.js 已生成`);
